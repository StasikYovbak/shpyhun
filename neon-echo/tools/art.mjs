/**
 * Рівномірне збільшення сітки піксель-арту (nearest-neighbour).
 * 12x15 -> 16x20 — це рівно 4/3 по обох осях, тож кожен третій
 * стовпчик і рядок дублюється. Малюнок лишається той самий, просто
 * крупніший: жодного нового кольору й жодної нової деталі, як і
 * вимагалось для героїні ще з версії 5.
 */
export function upscale(rows, w2, h2) {
  const h = rows.length, w = rows[0].length, out = [];
  for (let y = 0; y < h2; y++) {
    const sy = Math.min(h - 1, Math.floor(y * h / h2));
    let line = '';
    for (let x = 0; x < w2; x++) line += rows[sy][Math.min(w - 1, Math.floor(x * w / w2))];
    out.push(line);
  }
  return out;
}

/* ==================================================================
   КАДРИ АТАКИ ПІД КОЖНУ ЗБРОЮ
   Героїня має рухатись по-різному залежно від того, що тримає в руках,
   а не міняти лише ефект. Кожна поза тут — це базова фігура плюс
   кілька правок: рука туди, корпус нижче, плечі в розворот. Так у коді
   видно НАМІР кадру («присів і б'є вниз усією вагою»), а не сітка
   крапок, у якій нічого не розбереш і яку страшно правити.
     '.' у правці — не чіпати, '_' — стерти до прозорого.
   ================================================================== */
const W = 12, H = 15;
function edit(rows, ops) {
  const g = rows.map(r => r.split(''));
  for (const [x, y, s] of ops)
    for (let i = 0; i < s.length; i++) {
      const c = s[i], xx = x + i;
      if (c === '.' || xx < 0 || xx >= W || y < 0 || y >= H) continue;
      g[y][xx] = (c === '_') ? '.' : c;
    }
  return g.map(r => r.join(''));
}
/** Зсув частини фігури по горизонталі: нахил уперед або відкид назад. */
function shift(rows, dx, y0, y1) {
  return rows.map((r, y) => {
    if (y < y0 || y > y1) return r;
    let out = '';
    for (let x = 0; x < W; x++) { const sx = x - dx; out += (sx < 0 || sx >= W) ? '.' : r[sx]; }
    return out;
  });
}
/** Присід: уся фігура осідає на два ряди, ноги згинаються. */
function crouch(rows) {
  const out = ['............', '............'];
  for (let y = 0; y <= 9; y++) out.push(rows[y]);
  out.push('..33....33..', '.88......88.', '............');
  return out;
}
/** Розворот корпусу: плечі стають ребром, ноги зводяться. */
function turn(rows) {
  const g = rows.slice();
  for (let y = 6; y <= 10; y++) g[y] = g[y].replace('344443', '.3443.');
  g[11] = '....33......'; g[12] = '....33......'; g[13] = '...888......';
  return g;
}
/** Спиною до камери: візора не видно, натомість волосся по спині. */
function back(rows) {
  const g = rows.slice();
  g[2] = '..22222222..'; g[3] = '..22222222..'; g[4] = '..22222222..';
  g[5] = '...222222...';
  return g;
}

