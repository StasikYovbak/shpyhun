/**
 * Три режими складності — через МЕХАНІКИ, не через циферки.
 *
 * Головне правило прямо з ТЗ: HP і урон босів між режимами не міняються
 * більше ніж на ±10 %. Тут вони не міняються взагалі — рівно 0 %, щоб
 * це можна було перевірити тестом, а не повірити на слово. «Більше
 * здоров'я» — це не складність, це довший бій із тими самими рухами.
 *
 * Різниця в тому, ЩО бос робить: скільки патернів у нього в наборі,
 * скільки триває попередження, скільки відкрите вікно шкоди й чи
 * вмикаються пастки арени.
 *
 * Режим міняється будь-коли й нічого не блокує: ні нагороди, ні
 * сектори, ні кінцівку.
 */

export const DIFFS = ['easy', 'normal', 'hard'];
export const DIFF_NAME = { easy: 'Легкий', normal: 'Середній', hard: 'Максимальний' };

/** Активні множники. Читається геймплеєм щокадру, тож — простий об'єкт. */
export const D = {
  key: 'normal',
  hp: 1,            // множник HP боса — навмисно 1 на всіх режимах
  dmg: 1,           // множник урону боса — так само 1
  tel: 1,           // тривалість телеграфів
  win: 1,           // тривалість вікон вразливості
  iframe: 1,        // кадри невразливості гравця після шкоди
  rageAt: 120,      // секунд бою до люті; 0 = люті немає
  medkit: 0,        // період відновлення аптечок на арені, с; 0 = не відроджуються
  hazard: 1,        // пастки арени під час бою з босом
  dropHardest: 0,   // прибрати найважчий патерн боса
  p3new: 1,         // чи дає фаза 3 нові патерни (чи лише прискорення)
  bossRestart: 0,   // смерть -> одразу з боса, без втрат
  parry: 0.15,      // вікно парирування, с
  parryK: 2,        // множник шкоди відбитої кулі
  mobTrait: 0,      // мобам +1 поведінкова риса
  extra: 0          // босу — окрема нова механіка
};

const TABLE = {
  easy: {
    tel: 1.40, win: 1.50, iframe: 1.50, rageAt: 0, medkit: 30, hazard: 0,
    dropHardest: 1, p3new: 0, bossRestart: 1, parry: 0.15, parryK: 2, mobTrait: 0, extra: 0
  },
  normal: {
    tel: 1, win: 1, iframe: 1, rageAt: 120, medkit: 0, hazard: 1,
    dropHardest: 0, p3new: 1, bossRestart: 0, parry: 0.15, parryK: 2, mobTrait: 0, extra: 0
  },
  hard: {
    tel: 1, win: 0.75, iframe: 1, rageAt: 90, medkit: 0, hazard: 1,
    dropHardest: 0, p3new: 1, bossRestart: 0,
    // Вужче вікно, але відбита куля б'є втричі: ризик і нагорода ростуть разом.
    parry: 0.10, parryK: 6, mobTrait: 1, extra: 1
  }
};

export function setDiff(key) {
  D.key = DIFFS.indexOf(key) >= 0 ? key : 'normal';
  const t = TABLE[D.key];
  for (const k of Object.keys(t)) D[k] = t[k];
  D.hp = 1; D.dmg = 1;                     // ще раз явно: цифри боса не чіпаються
  return D.key;
}

