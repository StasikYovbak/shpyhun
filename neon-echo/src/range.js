/**
 * Будує карту. Повертає той самий формат, що й LEVELS: масив рядків.
 * Заразом віддає точні координати всього, що має бути підписане.
 */
export function buildRange() {
  const g = [];
  for (let y = 0; y < H; y++) g.push(new Array(W).fill('.'));

  const solid = (x, y) => { if (x >= 0 && x < W && y >= 0 && y < H) g[y][x] = '#'; };
  const col = (x, y0, y1) => { for (let y = y0; y <= y1; y++) solid(x, y); };

  // Суцільна підлога під усією кімнатою; прірви вирізаємо потім.
  for (let x = 0; x < W; x++) col(x, FLOOR, H - 1);
  // Стіни по краях, щоб не вийти за карту
  col(0, 0, H - 1); col(1, 0, H - 1);
  col(W - 1, 0, H - 1); col(W - 2, 0, H - 1);

  const marks = { gaps: [], walls: [] };

  /* --- зона платформінгу: спершу прірви, потім стіни --- */
  const plat = ZONES[2];
  let x = plat.x0 + 3;
  for (const n of GAPS) {
    for (let i = 0; i < n; i++) for (let y = FLOOR; y < H; y++) g[y][x + i] = '.';
    marks.gaps.push({ n: n, x0: x, x1: x + n - 1 });
    x += n + 4;                                    // 4 тайли розбігу між прірвами
  }
  for (const h of WALLS) {
    col(x, FLOOR - h, FLOOR - 1);
    marks.walls.push({ h: h, x: x });
    x += 5;                                        // місце на розбіг і приземлення
  }

  // Одна рухома платформа наприкінці зони платформінгу: на ній
  // перевіряється правило передачі імпульсу при стрибку.
  const mpx = x + 2;
  marks.mp = { x: mpx, y: FLOOR - 3 };
  return {
    n: 'ТРЕНУВАЛЬНА КІМНАТА', th: 'virtual', boss: null,
    mp: [[mpx, FLOOR - 3, 3, 'h', 6, 60]],
    rows: g.map(r => r.join('')),
    range: true, marks: marks
  };
}

