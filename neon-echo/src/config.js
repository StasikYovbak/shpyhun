/* ================================================================
   SCALE — ЄДИНИЙ КОЕФІЦІЄНТ МАСШТАБУ ГРИ
   Змінити тут — і виросте ВСЕ: тайл, хітбокси, швидкість бігу,
   гравітація, висота стрибка, дальність зброї, дуги атак, радіуси
   вибухів, розліт часток. Саме тому геометрія рівнів у ТАЙЛАХ не
   змінюється, і прохідність зберігається без жодної правки карт.

   Минулого разу спрайти виросли разом із роздільністю — і на екрані
   це не відчулось, бо пропорція лишилась та сама. Тепер інакше:
   світ росте в 1,5 раза, а кадр — лише в 1,21. Героїня займає на
   екрані на 26 % більше, і це вже видно.

   Правило одиниць: множимо ДОВЖИНИ, ШВИДКОСТІ й ПРИСКОРЕННЯ.
   Часи, частки й одиниці шкоди лишаються як є — інакше поїде
   і відчуття керування, і баланс.
   ================================================================ */
export const SCALE = 1.5;
/** Довжина / швидкість / прискорення у світових пікселях. */
export const S = v => v * SCALE;
/** Те саме, але цілим: для розмірів сітки й хітбоксів. */
export const Si = v => Math.max(1, Math.round(v * SCALE));

/* Кадр: 528x297 -> 640x360, це рівно x1,21. Разом зі світом x1,5
   персонаж виходить на екрані на чверть більшим. */
export const VW = 640, VH = 360;
export const TS = Si(16);                          // тайл 16 -> 24 px

