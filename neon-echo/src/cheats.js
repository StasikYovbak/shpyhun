/**
 * Стан читів режиму розробника. Окремий крихітний модуль без жодного
 * побічного ефекту — саме тому при `DEV_MODE = false` Rollup викидає і
 * його, і всі звернення до нього: у грі кожне читання стоїть під
 * `if (DEV_MODE && CH.…)`, а панель (src/debug.js) підвантажується
 * динамічним import'ом теж під `if (DEV_MODE)`.
 *
 * ПРАВИЛО: чити накладаються ПОВЕРХ базових значень і нічого не
 * переписують. Вимкнув чит — гра поводиться рівно як до нього, без
 * залишкових ефектів. Тому тут лише множники й прапорці, а не копії
 * ігрових констант.
 */
export const CH = {
  /* --- бій --- */
  invuln: 0,        // безсмертя
  dmgK: 1,          // множник урону гравця: 1 / 5 / 20
  oneShot: 0,       // «вбиває з одного удару» (перебиває dmgK)
  res: 0,           // нескінченні ресурси: тепло, ядра, набої, дрони
  dash: 0,          // ривок без кулдауну

  /* --- рух --- */
  fly: 0,           // політ і noclip: крізь стіни, без гравітації
  speed: 1,         // множник швидкості гри: 0.25 / 0.5 / 1 / 2 / 4
  frozen: 0,        // покадровий режим: гра стоїть
  stepOnce: 0,      // ...і робить рівно один крок на запит
  jump3: 0,         // потрійний стрибок (+1 стрибок у повітрі)

  /* --- діагностика (не чити: поведінку гри не міняють) --- */
  diag: 0,          // цифри поверх гри: FPS, спрайти, координати, пули
  boxes: 0,         // хітбокси героїні, ворогів, атак і тайлів
  grid: 0,          // сітка тайлів і лінія підлоги
  ai: 0,            // стан ШІ кожного ворога, лінія до цілі, токен атаки
  errs: 0           // останні помилки з консолі
};

/** Чи активний хоч один чит — для червоної рамки й напису GOD MODE. */
export function cheating() {
  return !!(CH.invuln || CH.oneShot || CH.res || CH.dash || CH.fly ||
            CH.jump3 || CH.frozen || CH.dmgK !== 1 || CH.speed !== 1);
}

/** Вимкнути геть усі чити (діагностику лишаємо — вона нічого не міняє). */
export function cheatsOff() {
  CH.invuln = CH.oneShot = CH.res = CH.dash = CH.fly = CH.jump3 = 0;
  CH.frozen = CH.stepOnce = 0;
  CH.dmgK = 1; CH.speed = 1;
}
